// Builds lib/whoGrowth.ts from the WHO Child Growth Standards (0–5 years),
// the LMS tables published by the WHO in its "anthro" package:
//   https://github.com/WorldHealthOrganization/anthro (data-raw/growthstandards)
// weianthro.txt (weight-for-age), lenanthro.txt (length/height-for-age),
// hcanthro.txt (head circumference-for-age). Ages there are in days; this
// keeps one row per month (age in days = round(month × 30.4375)).
//
//   node scripts/who-growth/make.mjs <folder with the three .txt files>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder that holds weianthro.txt, lenanthro.txt and hcanthro.txt");

function read(file) {
  const [, ...lines] = readFileSync(join(dir, file), "utf8").trim().split(/\r?\n/);
  const rows = new Map();
  for (const line of lines) {
    const [sex, age, l, m, s] = line.split("\t");
    rows.set(`${sex}:${age}`, [Number(l), Number(m), Number(s)]);
  }
  return rows;
}

const out = {};
for (const [key, file] of [["weight", "weianthro.txt"], ["height", "lenanthro.txt"], ["head", "hcanthro.txt"]]) {
  const rows = read(file);
  out[key] = {};
  for (const [sex, name] of [["1", "m"], ["2", "f"]]) {
    const series = [];
    for (let month = 0; month <= 60; month++) {
      const r = rows.get(`${sex}:${Math.round(month * 30.4375)}`);
      if (!r) throw new Error(`missing ${file} ${sex} month ${month}`);
      series.push(r);
    }
    out[key][name] = series;
  }
}

const body = `// GENERATED by scripts/who-growth/make.mjs. Do not edit by hand.
// WHO Child Growth Standards, 0–60 months: [L, M, S] per month for boys (m)
// and girls (f). Weight in kg; length (to 24 months) then height in cm;
// head circumference in cm. Source: WHO, https://github.com/WorldHealthOrganization/anthro

export type Lms = readonly [number, number, number];
export const WHO_GROWTH: Record<"weight" | "height" | "head", Record<"m" | "f", readonly Lms[]>> = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../../lib/whoGrowthData.ts", import.meta.url), body);
console.log("Wrote lib/whoGrowthData.ts");
